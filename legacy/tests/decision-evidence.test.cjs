const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const src=fs.readFileSync(__dirname+'/../app.js','utf8');
const ctx={localStorage:{getItem:()=>null},alert:()=>{},document:{querySelector:()=>null},Date,console};
vm.createContext(ctx);
vm.runInContext(src.slice(0,src.indexOf('function header()'))+'\nthis.api={decisionEvidence,evidenceCard,weekPlan};',ctx);
const p={goal:'forza',level:'ripresa',days:2,duration:30,equipment:[],trainingDays:[],unavailableDays:[]};
const first=ctx.api.weekPlan(p,'2026-11-02',null);
assert(ctx.api.decisionEvidence(first,null,[]).observed[0].includes('Nessuna settimana'));
first.sessions[0].completed=true;first.sessions[0].status='done';first.sessions[0].feedback={effort:'easy',pain:'no'};
first.sessions[1].completed=true;first.sessions[1].status='done';first.sessions[1].feedback={effort:'easy',pain:'no'};
const next=ctx.api.weekPlan(p,'2026-11-09',first);
assert(next.decisionSource&&next.decisionSource.start==='2026-11-02');
const evidence=ctx.api.decisionEvidence(next,next.decisionSource,[]);
assert(evidence.observed.some(x=>x.includes('2 sedute complete')));
assert(evidence.rules.some(x=>x.includes('possibile piccolo incremento')));
assert(ctx.api.evidenceCard(next,next.decisionSource,[]).includes('Dati osservati'));
first.sessions[0].feedback.pain='yes';
const caution=ctx.api.weekPlan(p,'2026-11-09',first);
assert(ctx.api.decisionEvidence(caution,caution.decisionSource,[]).rules.some(x=>x.includes('Fastidi')));
console.log('PASS: motivazioni tracciabili, progressione e fastidi');
