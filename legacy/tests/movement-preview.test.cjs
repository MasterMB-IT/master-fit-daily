const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const src=fs.readFileSync(__dirname+'/../app.js','utf8');
const catalog=JSON.parse(fs.readFileSync(__dirname+'/../exercise-catalog.json','utf8')).exercises;
const ctx={window:{MASTER_FIT_CATALOG:catalog},localStorage:{getItem:()=>null,setItem:()=>{}},document:{querySelector:()=>null},Date,console};
